import { readFile, writeFile } from "node:fs/promises";
import { getAddress } from "viem";

const [marketsPath, coinsPath, tokenListPath, outputPath] =
  process.argv.slice(2);

if (!marketsPath || !coinsPath || !tokenListPath || !outputPath) {
  throw new Error(
    "Usage: node tooling/update-ethereum-token-registry.mjs <markets.json> <coins-list.json> <token-list.json> <output.ts>",
  );
}

const [markets, coins, tokenList] = await Promise.all([
  readJson(marketsPath),
  readJson(coinsPath),
  readJson(tokenListPath),
]);

const coinsById = new Map(coins.map((coin) => [coin.id, coin]));
const tokensByAddress = new Map(
  tokenList.tokens
    .filter((token) => token.chainId === 1)
    .map((token) => [token.address.toLowerCase(), token]),
);

const reviewed = markets
  .map((market) => {
    const address = coinsById.get(market.id)?.platforms?.ethereum;
    if (!/^0x[0-9a-fA-F]{40}$/.test(address ?? "")) return null;
    const metadata = tokensByAddress.get(address.toLowerCase());
    if (!metadata || !Number.isInteger(metadata.decimals)) return null;
    return {
      address: getAddress(address),
      symbol: metadata.symbol || market.symbol.toUpperCase(),
      name: metadata.name || market.name,
      decimals: metadata.decimals,
      marketId: market.id,
    };
  })
  .filter(Boolean)
  .filter(
    (token, index, all) =>
      all.findIndex(
        (candidate) =>
          candidate.address.toLowerCase() === token.address.toLowerCase(),
      ) === index,
  )
  .slice(0, 250)
  .map((token, index) => ({ ...token, snapshotRank: index + 1 }));

if (reviewed.length !== 250) {
  throw new Error(
    `Expected 250 reviewed Ethereum tokens, received ${reviewed.length}`,
  );
}

const header = `// Generated by tooling/update-ethereum-token-registry.mjs.\n// Runtime code never contacts the ranking or metadata sources.\n`;
const body = `export const ethereumTop250Snapshot = ${JSON.stringify(reviewed, null, 2)} as const;\n`;
await writeFile(outputPath, header + body);

async function readJson(path) {
  return JSON.parse(await readFile(path, "utf8"));
}
