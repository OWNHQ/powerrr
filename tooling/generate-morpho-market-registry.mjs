import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import prettier from "prettier";

const ZERO_ADDRESS = "0x0000000000000000000000000000000000000000";
const DEFAULT_OUTPUT = "packages/configs/src/ethereum-morpho-usdc-markets.ts";

const [reportArgument, mode = "--write"] = process.argv.slice(2);
if (!reportArgument || !["--write", "--check"].includes(mode)) {
  throw new Error(
    "Usage: node tooling/generate-morpho-market-registry.mjs <provider-audit.json> [--write|--check]",
  );
}

const reportPath = resolve(reportArgument);
const outputPath = resolve(DEFAULT_OUTPUT);
const report = JSON.parse(await readFile(reportPath, "utf8"));
const rows = report?.providers?.morpho?.rows;
if (!Array.isArray(rows) || rows.length === 0) {
  throw new Error("The provider audit did not contain Morpho market rows.");
}

const markets = rows
  .filter((row) => row.identityVerified === true)
  .map((row) => ({
    marketId: row.marketId,
    createdAtBlock: row.createdAtBlock,
    loanToken: "0xA0b86991c6218b36c1d19D4a2e9Eb0cE3606eB48",
    loanSymbol: "USDC",
    loanDecimals: 6,
    collateralToken: row.address,
    collateralSymbol: row.symbol,
    collateralName: row.name,
    collateralDecimals: row.decimals,
    oracle: row.oracle,
    irm: row.irm,
    lltv: row.lltv,
  }))
  .sort((left, right) => left.marketId.localeCompare(right.marketId));

if (
  new Set(markets.map((market) => market.marketId.toLowerCase())).size !==
  markets.length
) {
  throw new Error(
    "The official Morpho response contained duplicate market IDs.",
  );
}

const priceCandidates = new Map();
for (const row of rows) {
  if (
    row.identityVerified !== true ||
    String(row.address).toLowerCase() === ZERO_ADDRESS ||
    String(row.oracle).toLowerCase() === ZERO_ADDRESS ||
    BigInt(row.oraclePriceRaw ?? "0") <= 0n
  )
    continue;
  const key = String(row.address).toLowerCase();
  const current = priceCandidates.get(key);
  const liquidity = BigInt(row.availableLiquidityRaw ?? "0");
  if (
    !current ||
    liquidity > current.liquidity ||
    (liquidity === current.liquidity && row.marketId < current.marketId)
  ) {
    priceCandidates.set(key, { row, liquidity, marketId: row.marketId });
  }
}

const collateralByAddress = new Map();
for (const market of markets) {
  const key = market.collateralToken.toLowerCase();
  if (
    key === ZERO_ADDRESS ||
    !Number.isInteger(market.collateralDecimals) ||
    market.collateralDecimals <= 0 ||
    market.collateralDecimals > 36
  ) {
    continue;
  }
  const existing = collateralByAddress.get(key);
  if (existing) {
    if (existing.decimals !== market.collateralDecimals) {
      throw new Error(`Conflicting decimals for ${market.collateralToken}.`);
    }
    continue;
  }
  const candidate = priceCandidates.get(key)?.row;
  collateralByAddress.set(key, {
    address: market.collateralToken,
    symbol: market.collateralSymbol,
    name: market.collateralName,
    decimals: market.collateralDecimals,
    ...(candidate
      ? {
          priceMarketId: candidate.marketId,
          priceOracle: candidate.oracle,
        }
      : {}),
  });
}
const collateralTokens = [...collateralByAddress.values()].sort((left, right) =>
  left.address.toLowerCase().localeCompare(right.address.toLowerCase()),
);

const source = `// Generated by tooling/generate-morpho-market-registry.mjs. Do not edit manually.\n\nexport type MorphoMarketRegistryEntry = {\n  marketId: \`0x\${string}\`;\n  createdAtBlock: string;\n  loanToken: \`0x\${string}\`;\n  loanSymbol: \"USDC\";\n  loanDecimals: 6;\n  collateralToken: \`0x\${string}\`;\n  collateralSymbol: string;\n  collateralName: string;\n  collateralDecimals: number;\n  oracle: \`0x\${string}\`;\n  irm: \`0x\${string}\`;\n  lltv: string;\n};\n\nexport type MorphoCollateralRegistryEntry = {\n  address: \`0x\${string}\`;\n  symbol: string;\n  name: string;\n  decimals: number;\n  priceMarketId?: \`0x\${string}\`;\n  priceOracle?: \`0x\${string}\`;\n};\n\nexport const ETHEREUM_MORPHO_USDC_MARKET_MANIFEST_VERSION =\n  \"ethereum-morpho-usdc-${report.block.number}-v1\";\nexport const ETHEREUM_MORPHO_USDC_MARKET_SOURCE_BLOCK = \"${report.block.number}\";\nexport const ETHEREUM_MORPHO_USDC_MARKET_SOURCE_HASH =\n  \"${report.block.hash}\";\nexport const ETHEREUM_MORPHO_USDC_OFFICIAL_LISTED_COUNT = ${rows.length};\n\nexport const ethereumMorphoUsdcMarketsV1 = ${JSON.stringify(markets, null, 2)} as const satisfies readonly MorphoMarketRegistryEntry[];\n\nexport const ethereumMorphoCollateralTokensV1 = ${JSON.stringify(collateralTokens, null, 2)} as const satisfies readonly MorphoCollateralRegistryEntry[];\n`;

const formattedSource = await prettier.format(source, {
  parser: "typescript",
});

if (mode === "--check") {
  const existing = await readFile(outputPath, "utf8").catch(() => "");
  if (existing !== formattedSource) {
    throw new Error(
      "The checked-in Morpho registry differs from the official audited set. Regenerate it before release.",
    );
  }
  console.log(
    JSON.stringify({
      status: "current",
      markets: markets.length,
      collateralTokens: collateralTokens.length,
    }),
  );
} else {
  await writeFile(outputPath, formattedSource);
  console.log(
    JSON.stringify({
      outputPath: DEFAULT_OUTPUT,
      markets: markets.length,
      collateralTokens: collateralTokens.length,
    }),
  );
}
